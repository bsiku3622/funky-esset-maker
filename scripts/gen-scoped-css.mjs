/* Regenerate the per-tool scoped CSS for the unified app.
 *
 * The source tools were originally standalone projects (Highlighter, Tabler,
 * …). Their App.css is vendored under tool-sources/<Tool>/App.css so this repo
 * is self-contained. That CSS uses global class names (.toolbar, .stage, .shot,
 * …) that collide when merged, so we prefix every selector with the tool's
 * scope class (.scope-highlighter .toolbar { … }) to isolate them — pure CSS,
 * no @scope.
 *
 * To pull in upstream style changes, recopy the standalone project's
 * src/App.css over tool-sources/<Tool>/App.css, then run:
 *   npm run gen:css
 *
 * Run from the project root (npm sets cwd there).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = process.cwd() // .../Funky Esset Maker
const SOURCES = join(ROOT, 'tool-sources') // vendored standalone-tool App.css
const OUT = join(ROOT, 'src', 'tools')

// source dir | output css basename | scope class
const TOOLS = [
  ['Highlighter', 'Highlighter', 'scope-highlighter'],
  ['LaTeXiMaGeR', 'LatexImager', 'scope-latex'],
  ['Tabler', 'Tabler', 'scope-tabler'],
  ['DS Visualizer', 'DsVisualizer', 'scope-dsviz'],
  ['Grapher', 'Grapher', 'scope-grapher'],
]

// Prefix every selector with `.scope`, dropping :root (its vars are hoisted to
// the app's global index.css). The tool CSS is flat (no nested at-rules), so
// brace depth only toggles 0<->1 and a simple scan is enough.
function prefixCss(css, scope) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '') // strip comments
  let out = `/* GENERATED by scripts/gen-scoped-css.mjs — do not edit by hand.\n   source: ../<tool>/src/App.css, selectors prefixed with .${scope} */\n`
  let i = 0
  const n = css.length
  while (i < n) {
    const open = css.indexOf('{', i)
    if (open === -1) break
    const sel = css.slice(i, open).trim()
    let close = css.indexOf('}', open)
    if (close === -1) close = n
    const body = css.slice(open + 1, close).trim()
    i = close + 1
    if (!sel) continue
    const prefixed = sel
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean)
      .filter((s) => s !== ':root')
      .map((s) => `.${scope} ${s}`)
      .join(',\n')
    if (!prefixed) continue // e.g. a :root-only rule
    out += `${prefixed} {\n  ${body}\n}\n`
  }
  return out
}

for (const [dir, name, scope] of TOOLS) {
  const srcPath = join(SOURCES, dir, 'App.css')
  if (!existsSync(srcPath)) {
    // Vendored source is absent — keep the committed src/tools/<name>.css as the
    // fallback and move on instead of failing the build.
    console.log(`  ${name}.css  --  skipped (no source at tool-sources/${dir})`)
    continue
  }
  const src = readFileSync(srcPath, 'utf8')
  const result = prefixCss(src, scope)
  writeFileSync(join(OUT, `${name}.css`), result)
  console.log(`  ${name}.css  <-  ${dir}  (.${scope})  ${result.length} bytes`)
}
console.log('done.')
